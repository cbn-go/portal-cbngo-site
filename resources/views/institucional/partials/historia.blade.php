<div class="space-y-5 text-neutral-700 leading-relaxed">
    <p>
        A <strong>Convenção Batista Nacional (CBN)</strong> nasceu em <strong>16 de setembro de 1967</strong>, fruto de um movimento de renovação espiritual que alcançou igrejas batistas em todo o Brasil. Conduzido por brasileiros, esse movimento deu à convenção o nome que carrega até hoje: <em>nacional</em>.
    </p>
    <p>
        Desde o início, Goiás esteve no caminho dessa história. Igrejas goianas abraçaram a ênfase no avivamento, nas missões, na cooperação e na unidade na diversidade, os quatro pilares representados no logotipo da CBN, e passaram a se organizar como seção estadual para cuidar de pessoas, plantar novas congregações e servir às comunidades do interior e da capital.
    </p>
    <p>
        Foi também em solo goiano, na cidade de <strong>Luziânia</strong>, que os batistas nacionais se reuniram para firmar o <strong>Pacto Renovado</strong>, um compromisso de restauração do altar, da unidade e da conduta cristã que orienta a convenção até hoje.
    </p>
    <p>
        Hoje a CBN-GO reúne congregações em diversos municípios do estado, articuladas em coordenações regionais, e caminha com a CBN nacional, que soma cerca de 2.700 igrejas e mais de 400 mil membros, além de missionários em vários continentes.
    </p>
</div>
